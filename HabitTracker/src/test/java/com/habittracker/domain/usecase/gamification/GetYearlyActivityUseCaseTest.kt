package com.habittracker.domain.usecase.gamification

import com.habittracker.domain.model.HabitEntry
import com.habittracker.domain.model.Habit
import com.habittracker.domain.model.HabitType
import com.habittracker.domain.model.gamification.ActivityLevel
import com.habittracker.domain.repository.HabitEntryRepository
import com.habittracker.domain.repository.HabitRepository
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.flow.flowOf
import kotlinx.coroutines.test.runTest
import kotlin.time.Clock
import kotlinx.datetime.DateTimeUnit
import kotlinx.datetime.TimeZone
import kotlinx.datetime.minus
import kotlinx.datetime.plus
import kotlinx.datetime.todayIn
import org.junit.Assert.assertEquals
import org.junit.Before
import org.junit.Test
import org.mockito.Mock
import org.mockito.Mockito.`when`
import org.mockito.MockitoAnnotations

class GetYearlyActivityUseCaseTest {

    @Mock
    private lateinit var habitEntryRepository: HabitEntryRepository
    @Mock
    private lateinit var habitRepository: HabitRepository

    private lateinit var getYearlyActivityUseCase: GetYearlyActivityUseCase

    @Before
    fun setUp() {
        MockitoAnnotations.openMocks(this)
        getYearlyActivityUseCase = GetYearlyActivityUseCase(habitEntryRepository, habitRepository)
    }

    @Test
    fun `invoke returns correct activity levels for last year`() = runTest {
        // Given
        val userId = "test_user"
        val today = Clock.System.todayIn(TimeZone.currentSystemDefault())
        val oneYearAgo = today.minus(365, DateTimeUnit.DAY)
        
        // Prepare mock data
        // Date 1: 0 counts -> NONE
        // Date 2: 2 counts -> LOW
        // Date 3: 4 counts -> MEDIUM
        // Date 4: 7 counts -> HIGH
        // Date 5: 12 counts -> VERY_HIGH
        
        val date1 = oneYearAgo.plus(1, DateTimeUnit.DAY)
        val date2 = oneYearAgo.plus(2, DateTimeUnit.DAY)
        val date3 = oneYearAgo.plus(3, DateTimeUnit.DAY)
        val date4 = oneYearAgo.plus(4, DateTimeUnit.DAY)
        val date5 = oneYearAgo.plus(5, DateTimeUnit.DAY)
        
        val habits = (1..12).map { idx ->
            Habit(id = "h$idx", title = "H$idx", type = HabitType.PERSONAL)
        }

        val entries = buildList {
            repeat(2) { add(entry(userId, "h${it + 1}", date2)) }
            repeat(4) { add(entry(userId, "h${it + 3}", date3)) }
            repeat(7) { add(entry(userId, "h${it + 7}", date4)) }
            repeat(12) { add(entry(userId, "h${it + 1}", date5)) }
        }

        `when`(habitEntryRepository.getEntriesForUser(userId)).thenReturn(flowOf(entries))
        `when`(habitRepository.getHabitsByUserId(userId)).thenReturn(flowOf(habits))
        `when`(habitRepository.getHabitParticipantSettings(org.mockito.kotlin.any(), org.mockito.kotlin.any())).thenReturn(null)

        // When
        val result = getYearlyActivityUseCase(userId).first()

        // Then
        // Result should cover 366 days (0..365)
        assertEquals(366, result.size)
        
        // Verify specific dates
        // Find entries matching our dates (assuming list is ordered by date which logic suggests)
        // The list is generated by iterating 0..365, so it is ordered.
        
        // date1 corresponds to index 1
        val entry1 = result.find { it.date == date1 }
        assertEquals(ActivityLevel.NONE, entry1?.level)
        
        val entry2 = result.find { it.date == date2 }
        assertEquals(ActivityLevel.LOW, entry2?.level)
        
        val entry3 = result.find { it.date == date3 }
        assertEquals(ActivityLevel.MEDIUM, entry3?.level)
        
        val entry4 = result.find { it.date == date4 }
        assertEquals(ActivityLevel.HIGH, entry4?.level)
        
        val entry5 = result.find { it.date == date5 }
        assertEquals(ActivityLevel.VERY_HIGH, entry5?.level)
        
        // Verify a date not in map (should be 0/NONE)
        val dateEmpty = oneYearAgo.plus(10, DateTimeUnit.DAY)
        val entryEmpty = result.find { it.date == dateEmpty }
        assertEquals(ActivityLevel.NONE, entryEmpty?.level)
        assertEquals(0, entryEmpty?.count)
    }

    private fun entry(userId: String, habitId: String, date: kotlinx.datetime.LocalDate): HabitEntry {
        return HabitEntry(
            habitId = habitId,
            userId = userId,
            date = date,
            completed = true,
            createdAt = date,
            updatedAt = date
        )
    }
}
